"""Same-job baseline-server reopen of a stopped, disposable modern save.

Only supporting host code. No source, schema, character rows, user save or
native executable is changed. Original .36 native bytes are authenticated, not
reconstructed from a predecessor manifest. Immutable payloads use explicit verified PRoot file binds;
mutable manifests and the restored game archive are independent regular files.
"""
from __future__ import annotations
import copy
import importlib
import json
from pathlib import Path
import secrets
import re
import time
from zipfile import ZipFile

import modern_runtime_donor as donor
import modern_validation as validation

BASELINE_MAP = {'bytes': 7475200,
    'sha256': 'fea96d0a20f5e245930abd0a97e8cc1da7c4ef4c83ff8a7d5a5c283ba8071363'}
BINDING = 'armport-server-metrics-binding.json'
CHANGED_FILES = {'game-package.tar.gz', 'client-manifest.json', 'runtime-manifest.json'}


def encoded(value):
    return (json.dumps(value, sort_keys=True, indent=2, allow_nan=False)+'\n').encode()


def asset_view(source, output, apk, native):
    """Restore actual donor bytes and prove every other payload unchanged.

    The source is already staged/admitted by the current modern run. Rehash it
    before binding. Never alter a source inode or its link count. Private
    mutable metadata is written with exclusive create; remaining view leaves
    are empty owned PRoot bind destinations, not payload copies.
    """
    source, output = Path(source), Path(output)
    validation.require(source.is_dir() and not source.is_symlink()
        and not output.exists() and not output.is_symlink(), 'Fresh baseline asset view required')
    docs = donor.inspect_donor(apk)
    with ZipFile(apk) as archive:
        original = archive.read('assets/runtime/game-package.tar.gz')
    original_pin = donor.raw_pin(original)
    validation.require(original_pin == docs['runtime-manifest.json']['files']['game-package.tar.gz'],
                       'Original donor game archive differs')
    disk_runtime = json.loads((source/'runtime-manifest.json').read_text())
    disk_client = json.loads((source/'client-manifest.json').read_text())
    files = disk_runtime['files']
    # Python may have generated bytecode while the two completed guests
    # imported helpers. It is not copied/bound into the baseline namespace.
    extras = set(source.iterdir()) - ({source/name for name in files} | {source/'runtime-manifest.json'})
    validation.require(all(path.name == '__pycache__' and path.is_dir() and not path.is_symlink() for path in extras),
                       'Unexpected modern asset source member')
    validation.require(all(files.get(name) == pin for name,pin in disk_client['files'].items())
        and 'armport_server_metrics' in disk_runtime
        and BINDING in files and BINDING in disk_client['files'], 'Modern source inventory/metrics differs')
    for name, expected in files.items():
        validation.require(re.fullmatch('[A-Za-z0-9_.-]+',name) and name not in ('.','..')
            and donor.pin(source/name) == expected, 'Modern source asset changed: '+name)
    source_pins = {name: donor.pin(source/name) for name in files}
    source_pins['runtime-manifest.json'] = donor.pin(source/'runtime-manifest.json')
    output.mkdir(mode=0o700)
    # These three leaves will have different metadata/bytes and MUST NOT share
    # an inode with the current candidate asset set.
    with (output/'game-package.tar.gz').open('xb') as stream:
        stream.write(original)
    previous, old_members = native.read_game_archive(output/'game-package.tar.gz')
    current, current_members = native.read_game_archive(source/'game-package.tar.gz')
    native.validate_predecessor(old_members['game-package.json'], 'thor_certified_startup')
    validation.require(native.THOR_PREDECESSOR_MAPSERVER == BASELINE_MAP
        and {key: previous['files']['MapServer.exe'][key] for key in ('bytes','sha256')} == BASELINE_MAP,
        'Wrong original modern MapServer')
    validation.require(native.previous_package(current) == previous
        and set(current_members) == set(old_members)
        and all(current_members[name] == raw for name,raw in old_members.items()
                if name not in ('MapServer.exe','game-package.json')),
        'Baseline restoration changed another native member or package ancestry')
    baseline_runtime, baseline_client = copy.deepcopy(disk_runtime), copy.deepcopy(disk_client)
    baseline_runtime.pop('armport_server_metrics')
    baseline_runtime['files'].pop(BINDING); baseline_client['files'].pop(BINDING)
    baseline_runtime['files']['game-package.tar.gz'] = original_pin
    baseline_client['files']['game-package.tar.gz'] = original_pin
    file_binds = []
    for name in files:
        if name not in CHANGED_FILES and name != BINDING:
            (output/name).touch(mode=0o600, exist_ok=False)
            file_binds.append((str(source/name), '/opt/coh/'+name))
    # New metadata is created, never edited through an immutable payload link.
    with (output/'client-manifest.json').open('xb') as stream:
        stream.write(encoded(baseline_client))
    baseline_runtime['files']['client-manifest.json'] = donor.pin(output/'client-manifest.json')
    with (output/'runtime-manifest.json').open('xb') as stream:
        stream.write(encoded(baseline_runtime))
    validation.require(all(donor.pin(output/name if name in CHANGED_FILES else source/name) == expected
        for name,expected in baseline_runtime['files'].items()), 'Baseline asset view inventory differs')
    validation.require(all(donor.pin(source/name) == expected for name,expected in source_pins.items()),
                       'Baseline view mutated candidate assets')
    for name in CHANGED_FILES:
        validation.require((source/name).stat().st_ino != (output/name).stat().st_ino,
                           'Baseline mutable metadata aliases current assets')
    expected_producer = importlib.import_module('game_diagnostic').mapserver_progress_contract(previous)['producer']
    validation.require(expected_producer['mapserver_sha256'] == BASELINE_MAP['sha256'],
                       'Original baseline progress producer differs')
    return {'runtime_manifest': baseline_runtime, 'client_manifest': baseline_client, 'file_binds':file_binds,
        'expected_producer': expected_producer, 'source_pins':source_pins,
        'provenance': {'scope': 'actual_original_modern_donor_server_asset_view',
            'donor_apk': donor.DONOR, 'game_archive': original_pin, 'mapserver': BASELINE_MAP,
            'changed_asset_files': sorted(CHANGED_FILES), 'removed_asset_files': [BINDING],
            'other_native_members_byte_identical': True, 'candidate_payload_bytes_unchanged': True,
            'arm64_client_dbserver_and_data_unchanged': True,
            'immutable_payload_storage': 'explicit_verified_proot_file_binds; source_link_counts_unchanged'}}


def admission(expected_producer):
    def validate(report, runtime_manifest):
        proof = report.get('character_reopen', {})
        session = report.get('session_id')
        validation.require(report.get('scope') == 'actual_character_reopen_guest'
            and isinstance(session,str) and re.fullmatch('[0-9a-f]{32}',session)
            and proof.get('session_id') == session
            and 'armport_server_metrics' not in runtime_manifest
            and BINDING not in runtime_manifest.get('files',{})
            and proof.get('mapserver_producer') == expected_producer,
            'Baseline session does not admit the actual original native producer')
        observed = proof.get('map_startup_observation', {}).get('1', {})
        validation.require(observed.get('actual_installed_mapserver') == BASELINE_MAP
            and observed.get('actual_launched_mapserver') == BASELINE_MAP
            and observed.get('source_package_mapserver_pin_equal') is True
            and observed.get('launch_path_binding_observed') is True
            and observed.get('native_ready_verified') is True,
            'Baseline actual prepared/launched MapServer byte proof differs')
        return {'session_id': session, 'producer': copy.deepcopy(expected_producer),
                'actual_mapserver': copy.deepcopy(BASELINE_MAP)}
    return validate


def run(interactive, command, work, evidence, proot, runtime, client, progress,
        modern_projector, modern_saved, modern_session, assets, apk, native):
    """Run one fresh baseline reopen after complete modern-session cleanup."""
    reopen = interactive.reopen
    result = {'format':1, 'scope':'modern_saved_data_reopened_by_original_modern_mapserver',
        'passed':False, 'physical_device_validated':False, 'performance_acceptance':False,
        'modern_saved_session_id':modern_session, 'map_ids_executed':[1]}
    baseline_projector = None
    original_projector = interactive.legacy_report
    try:
        validation.require(modern_saved.get('session_id') == modern_session
            and modern_saved.get('scope') == 'actual_character_reopen_guest'
            and modern_saved.get('passed') is True and modern_saved.get('cleanup_complete') is True
            and {'postgres_graceful','wine_prefix_stopped','owned_processes_reaped'} <= set(modern_saved.get('cleanup',{}))
            and all(modern_saved.get('cleanup',{}).values()), 'Modern save did not stop cleanly before baseline reopen')
        before = reopen.persistent_profile_identity(work)  # Requires no postmaster.pid/display socket.
        view = asset_view(assets, work/'baseline-assets', apk, native)
        result['assets'] = view['provenance']
        baseline_runtime = copy.deepcopy(runtime)
        baseline_runtime.pop('armport_server_metrics',None);baseline_runtime.pop('armport_server_metrics_build',None)
        baseline_runtime['files'] = copy.deepcopy(view['runtime_manifest']['files'])
        baseline_client = view['client_manifest']
        validation.require(baseline_runtime['armport_client'] == runtime['armport_client']
            and baseline_runtime['armport_server_native_closure'] == runtime['armport_server_native_closure'],
            'Baseline client or server data closure changed')
        documents = validation.contracts(assets, baseline_runtime)  # These unchanged manifests use file binds.
        # Restore the original shared projector before capturing it in the new
        # object. Do not chain the modern-metrics admission into a baseline run.
        interactive.legacy_report = modern_projector.legacy
        baseline_projector = validation.ModernProjector(interactive, baseline_runtime, baseline_client,
            documents, progress, admit_native=admission(view['expected_producer']))
        interactive.legacy_report = baseline_projector.project
        third = secrets.token_hex(16)
        validation.require(third != modern_session, 'Distinct baseline session required')
        reopen.archive_completed_reports(work/'state', modern_session)
        reopen.reset_session_requests(work/'state')
        # Keep the exact established command except its session/mode and one
        # authenticated asset-root bind. No new profile/import/data route.
        first_session = command[command.index('--session-id')+1]
        next_command = reopen.reopen_command(command, first_session, third)
        bind = str(assets)+':/opt/coh'
        validation.require(next_command.count(bind) == 1 and '--zoning' not in next_command,
                           'Unexpected baseline source asset bind or preselected route')
        next_command[next_command.index(bind)] = str(work/'baseline-assets')+':/opt/coh'
        extra_binds = [item for source,destination in view['file_binds'] for item in ('-b',source+':'+destination)]
        where = next_command.index('-w'); next_command[where:where] = extra_binds
        next_command.append('--zoning')
        deadline = time.monotonic()+interactive.character.OVERALL_SECONDS
        baseline = interactive.run_session(next_command, work, evidence/'baseline-reopen', proot,
            third, baseline_runtime, baseline_client, deadline, reopening=True)
        after = reopen.persistent_profile_identity(work)
        validation.require(all(donor.pin(assets/name) == expected for name,expected in view['source_pins'].items()),
                           'Baseline guest changed candidate source asset bytes')
        # The existing continuity checker consumes only the prior session's
        # actual saved proof. Its name is historical; no row/hash is invented.
        prior = dict(modern_saved, character_creation=modern_saved['character_reopen'])
        reopen.validate_continuity(prior, baseline, before, after)
        validation.require(set(baseline_projector.records) == {third}, 'Baseline native session admission missing')
        result.update(passed=True, baseline_session_id=third, same_persistent_profile=True,
            same_character_id=True, ordinary_save_and_reopen_validated=True,
            baseline_native_session=baseline_projector.records[third])
    except Exception as error:
        result['error'] = {'type':type(error).__name__,'message':str(error)}
        raise
    finally:
        interactive.legacy_report = original_projector
        (evidence/'baseline-compatibility-report.json').write_bytes(encoded(result))
    return result
