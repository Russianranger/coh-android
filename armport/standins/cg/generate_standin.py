#!/usr/bin/env python3
"""Generate cg_standin.cpp: the Cg/CgGL functions the client calls that
cg_arb.cpp does not implement, as stubs.

The original Cg runtime (cg.dll/cgGL.dll) is x86-only. cg_arb.cpp implements
the vertex/fragment program path over precompiled ARB assembly; every other
function (mostly CgFX effects) reports failure here (null handle, CG_FALSE,
CG_PROFILE_UNKNOWN, 0, or an empty string).

  python3 armport/standins/cg/generate_standin.py   (run from the repo root)
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
SRC = os.path.join(ROOT, 'upstream', 'ouroboros')
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'cg_standin.cpp')
IMPLEMENTED = os.path.join(HERE, 'cg_arb.cpp')
CALL = re.compile(r'\bcg(?:GL)?[A-Z][A-Za-z0-9]*(?=\s*\()')
HANDLES = {'CGcontext', 'CGprogram', 'CGparameter', 'CGeffect', 'CGtechnique', 'CGpass',
           'CGstate', 'CGstateassignment', 'CGannotation', 'CGobj', 'CGbuffer', 'CGhandle'}


def used_functions():
    names = set()
    for top in ('Game/src', 'Common', 'libs/UtilitiesLib'):
        for dirpath, _, files in os.walk(os.path.join(SRC, top)):
            for f in files:
                if f.endswith(('.c', '.cpp', '.h')):
                    text = open(os.path.join(dirpath, f), encoding='latin-1').read()
                    names.update(CALL.findall(text))
    return sorted(names)


def declarations():
    text = ''
    for h in ('cg.h', 'cgGL.h'):
        text += open(os.path.join(SRC, '3rdparty', 'cg', 'include', 'Cg', h), encoding='latin-1').read()
    decls = {}
    for m in re.finditer(r'(CG(?:GL)?_API)\s+([^;(]*?)\s*(CG(?:GL)?ENTRY)\s+(cg\w+)\s*\(([^;]*?)\)\s*;', text, re.S):
        decls[m.group(4)] = (m.group(2).strip(), m.group(3), ' '.join(m.group(5).split()))
    return decls


def failure_value(ret):
    r = ret.replace('const', '').strip()
    if r == 'void':
        return None
    if '*' in r:
        return '""' if r.replace(' ', '') == 'char*' else 'NULL'
    if r in HANDLES:
        return 'NULL'
    if r == 'CGbool':
        return 'CG_FALSE'
    if r == 'CGprofile':
        return 'CG_PROFILE_UNKNOWN'
    if r in ('CGtype', 'CGresource', 'CGenum', 'CGerror', 'CGdomain', 'CGGLenum'):
        return '(%s)0' % r
    return '0'


def implemented():
    text = open(IMPLEMENTED, encoding='latin-1').read()
    return set(re.findall(r'CG(?:GL)?ENTRY\s+(cg\w+)\s*\(', text))


def main():
    done = implemented()
    used = [u for u in used_functions() if u not in done]
    decls = declarations()
    missing = [u for u in used if u not in decls]
    if missing:
        raise SystemExit('not declared in the Cg headers: %s' % missing)
    out = ['/* GENERATED by generate_standin.py; do not edit. */',
           '/* ArmPort Cg stand-in: %d Cg/CgGL functions the client calls that cg_arb.cpp */' % len(used),
           '/* does not implement. Each one reports failure; see generate_standin.py. */',
           '#include <windows.h>', '#include <stddef.h>', '#include <Cg/cg.h>', '#include <Cg/cgGL.h>',
           '', '#if defined(__clang__)', '#pragma clang diagnostic ignored "-Wunused-parameter"', '#endif', '']
    for name in used:
        ret, entry, params = decls[name]
        out.append('%s %s %s(%s)' % (ret, entry, name, params))
        value = failure_value(ret)
        out.append('{')
        if value is not None:
            out.append('    return %s;' % value)
        out.append('}')
        out.append('')
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote %s with %d functions' % (os.path.relpath(OUT, ROOT), len(used)))


if __name__ == '__main__':
    main()
