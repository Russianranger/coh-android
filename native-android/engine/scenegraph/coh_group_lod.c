#include "coh_group_lod.h"
#include <math.h>
static int state_ok(const CohGroupLodState *s) {
    return isfinite(s->near_distance)&&isfinite(s->near_fade)&&isfinite(s->far_distance)&&
        isfinite(s->far_fade)&&isfinite(s->scale)&&isfinite(s->shadow_distance)&&
        s->from_file<=1&&s->from_trick<=1&&s->autogenerated<=1;
}
int coh_group_lod_apply_file_defaults(const CohGroupLodInput *in,CohGroupLodState *out) {
    CohGroupLodState s;int i;
    if(!in||!out||!state_ok(&in->prior)||in->model_present>1) return 0;
    s=in->prior;
    if(s.from_file) {
        if(!isfinite(in->file_scale)) return 0;
        if(!s.from_trick) {
            if(!isfinite(in->file_far)||!isfinite(in->file_far_fade)) return 0;
            s.far_distance=in->file_far;s.far_fade=in->file_far_fade;s.autogenerated=0;
        }
        s.scale=in->file_scale;
    }
    if(!s.scale)s.scale=1.f;
    if(!s.far_distance&&in->model_present) {
        float dv[3],maxrad;
        for(i=0;i<3;i++) {
            if(!isfinite(in->model_min[i])||!isfinite(in->model_max[i])||in->model_min[i]>in->model_max[i])return 0;
            dv[i]=in->model_max[i]-in->model_min[i];
        }
        maxrad=(float)sqrt(dv[0]*dv[0]+dv[1]*dv[1]+dv[2]*dv[2])*0.5f+s.shadow_distance;
        s.far_distance=10*(maxrad+10);s.autogenerated=1;
    }
    if(!s.far_fade&&in->model_present&&!s.from_trick) {
        s.far_fade=s.far_distance*0.25;s.autogenerated=1;
    }
    if(!state_ok(&s))return 0;
    *out=s;return 1;
}
