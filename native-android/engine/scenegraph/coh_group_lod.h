#ifndef COH_GROUP_LOD_H
#define COH_GROUP_LOD_H
#include <stdint.h>
/* State AFTER the source's trick/CLIENT ModelLODInfo stage. Caller must own and
 * qualify that stage; these numerical fields alone never prove its provenance. */
typedef struct CohGroupLodState {
    float near_distance,near_fade,far_distance,far_fade,scale,shadow_distance;
    uint32_t from_file,from_trick,autogenerated;
} CohGroupLodState;
typedef struct CohGroupLodInput {
    CohGroupLodState prior;
    float file_far,file_far_fade,file_scale;
    uint32_t model_present;
    float model_min[3],model_max[3];
} CohGroupLodInput;
/* Original groupSetLodValues numerical stage, constant work/no allocations.
 * Returns 1 on success, 0 on malformed/nonfinite/overflow input, leaving out
 * unchanged on refusal. Does not acquire auto-LOD resources or admit drawing. */
int coh_group_lod_apply_file_defaults(const CohGroupLodInput *,CohGroupLodState *out);
#endif
