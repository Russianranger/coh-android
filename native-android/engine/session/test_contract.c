#include <stdlib.h>
#include <string.h>
static unsigned checks;
#define CHECK(x) do {checks++;if(!(x)){fprintf(stderr,"contract line %d: %s\n",__LINE__,#x);exit(1);}}while(0)
typedef struct {uint8_t bytes[COH_PROTOCOL_FRAME_MAX];size_t length,calls;} Capture;
static CohStatus capture(void *context,CohBytes frame) {
    Capture *c=context;if(frame.size>sizeof(c->bytes))return COH_LIMIT;
    memcpy(c->bytes,frame.data,frame.size);c->length=frame.size;c->calls++;return COH_OK;
}
static CohNetPacket control(uint32_t id,uint32_t command,int encrypted,
    const uint8_t *public_key) {
    CohNetPacket p={0};CohProtocolBits b;p.id=id;
    CHECK(coh_protocol_bits_init(&b,p.payload,sizeof(p.payload),0,1)==0);
    CHECK(coh_protocol_write_pack(&b,1,0)==0);
    CHECK(coh_protocol_write_pack(&b,1,command)==0);
    if(command==2){CHECK(coh_protocol_write_pack(&b,1,(uint32_t)encrypted)==0);}
    p.payload_bits=(uint32_t)b.bit_length;
    if(public_key){size_t at=(b.cursor+7)&~(size_t)7;memcpy(p.payload+at/8,public_key,64);p.payload_bits=(uint32_t)(at+512);}
    return p;
}
static void deliver(CohNet *net,CohNetPacket p,CohBlowfish *key,uint64_t now) {
    uint8_t frame[COH_PROTOCOL_FRAME_MAX];size_t n=0;
    CHECK(coh_net_frame_encode(5,key,key!=NULL,&p,frame,sizeof(frame),&n)==COH_OK);
    CHECK(coh_net_receive(net,(CohBytes){frame,n},now)==COH_OK);
}
int main(void) {
    const CohAuthCrypto *provider=coh_auth_openssl_provider();
    uint8_t server_private[64],server_public[64],own[64],invalid[64]={0};
    CohBlowfish unchanged,key;
    CHECK(provider!=NULL);
    CHECK(coh_auth_dh_keypair(provider,server_private,server_public)==COH_OK);
    memset(own,0xa5,sizeof(own));memset(&key,0xa5,sizeof(key));unchanged=key;
    CHECK(coh_session_key_exchange(NULL,server_public,own,&key)==COH_INVALID);
    CHECK(memcmp(&key,&unchanged,sizeof(key))==0 && own[0]==0xa5);
    CHECK(coh_session_key_exchange((void *)provider,invalid,own,&key)==COH_INVALID);
    CHECK(memcmp(&key,&unchanged,sizeof(key))==0 && own[0]==0xa5);
    CohNetConfig config=coh_net_default_config();config.version=5;
    CohNet *net=coh_net_create(&config);CHECK(net);
    CHECK(coh_net_set_key_exchange(net,coh_session_key_exchange,(void *)provider,1)==COH_OK);
    CHECK(coh_net_begin(net,123,100)==COH_OK);
    Capture c={0};CHECK(coh_net_pump(net,100,capture,&c,(CohCancel){0})==COH_OK && c.calls==1);
    CohNetPacket ack=control(100,2,1,server_public);ack.ack_count=1;ack.acks[0]=1;
    deliver(net,ack,NULL,101);CHECK(coh_net_state(net)==COH_NET_WAIT_FINAL);
    CHECK(coh_net_pump(net,101,capture,&c,(CohCancel){0})==COH_OK && c.calls==2);
    CohNetPacket client_ack;
    CHECK(coh_net_frame_decode(5,NULL,0,0,(CohBytes){c.bytes,c.length},&client_ack)==COH_OK);
    CohProtocolBits b;uint32_t command;
    CHECK(coh_protocol_bits_init(&b,client_ack.payload,sizeof(client_ack.payload),client_ack.payload_bits,0)==0);
    CHECK(coh_protocol_read_pack(&b,1,&command)==0 && command==0);
    CHECK(coh_protocol_read_pack(&b,1,&command)==0 && command==3);
    CHECK(coh_protocol_read_pack(&b,1,&command)==0 && command==1);
    size_t at=(b.cursor+7)&~(size_t)7;CHECK(at+512==client_ack.payload_bits);
    CohBlowfish server_key;
    CHECK(coh_auth_dh_blowfish(provider,server_private,client_ack.payload+at/8,&server_key)==COH_OK);
    coh_auth_wipe(server_private,sizeof(server_private));
    CohNetPacket final=control(101,4,0,NULL);final.ack_count=1;final.acks[0]=client_ack.id;
    deliver(net,final,&server_key,102);CHECK(coh_net_state(net)==COH_NET_CONNECTED);
    /* CONNECT_MSG packet is generated by this test, not by a MapServer. */
    CohNetPacket map={0};map.id=102;
    CHECK(coh_protocol_bits_init(&b,map.payload,sizeof(map.payload),0,1)==0);
    CHECK(coh_protocol_write_pack(&b,1,COH_REP_CONNECT_MSG)==0);
    CHECK(coh_protocol_write_pack(&b,1,1)==0);
    CHECK(coh_protocol_write(&b,32,0)==0);map.payload_bits=(uint32_t)b.bit_length;
    deliver(net,map,&server_key,103);
    CohNetMessage message;CHECK(coh_net_next(net,&message)==COH_OK);
    CohRepSession replication;CohRepSchema schema={0};coh_rep_session_init(&replication);
    CHECK(coh_rep_session_begin(&replication,777)==COH_OK);
    CHECK(coh_rep_session_message(&replication,&schema,(CohBytes){message.payload,(message.payload_bits+7)/8},message.payload_bits,0,0,0)==COH_STATE);
    CHECK(replication.phase==COH_REP_WAIT_MAP);
    /* Explicit test-only authorization seam. NetLink CONNECTED is insufficient
     * to supply real Gate26 authorization in an application. */
    CHECK(coh_rep_session_message(&replication,&schema,(CohBytes){message.payload,(message.payload_bits+7)/8},message.payload_bits,0,0,1)==COH_OK);
    CHECK(replication.phase==COH_REP_MAP_CONNECTED && replication.selected_dbid==777);
    CHECK(coh_net_pump(net,104,capture,&c,(CohCancel){0})==COH_OK);
    coh_net_cancel(net);coh_net_destroy(net);coh_rep_session_disconnect(&replication);
    CHECK(replication.phase==COH_REP_DISCONNECTED && replication.selected_dbid==0);
    coh_auth_wipe(&server_key,sizeof(server_key));coh_auth_wipe(&unchanged,sizeof(unchanged));coh_auth_wipe(&key,sizeof(key));
    printf("{\"passed\":true,\"checks\":%u,\"encrypted_netlink_contract\":true,\"replication_authorization_guard\":true,\"real_server\":false,\"authenticated_account\":false,\"live_world\":false}\n",checks);
    return 0;
}
