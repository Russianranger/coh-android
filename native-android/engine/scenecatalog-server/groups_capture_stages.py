"""Fixed internal diagnostic stages; never derive a label from private input."""
CAPTURE_STAGES=('INPUT_COPY','WINE_VERSION','WINE_BOOT','RUNTIME_STAGE','PE_ADMISSION',
    'ODBC_INSTALL','ODBC_PROBE','POSTGRES_INITIALIZE','DATABASE_RESTORE','DBSERVER_START',
    'DBSERVER_READY','MAPSERVER_START','MAPSERVER_READY','NATIVE_CAPTURE','PAIR_VERIFY',
    'RETAIN_PRIVATE_PAIR','CLEANUP','COMPLETE')
FAILURE_STAGES=('NONE','PREFLIGHT','RECEIPT_INVALID',*CAPTURE_STAGES[:-1])
def advance(report,stage):
    if stage not in CAPTURE_STAGES:raise ValueError('CAPTURE_STAGE_INVALID')
    report['capture_stage']=stage
