#!/usr/bin/env python3
"""Deterministic build-time embedding; --check detects stale generated sources."""
import argparse,json
from pathlib import Path
p=Path(__file__).resolve().parent
v=(p/'shaders/rigid.vert').read_text()
f=(p/'shaders/material.frag.in').read_text()
text='/* Generated by embed_shaders.py. */\nstatic const char vertex_shader[] = '+json.dumps(v)+';\n'
text+='static const char vertex_shader_320[] = '+json.dumps(v.replace('#version 300 es','#version 320 es').replace('#define COH_PRECISE\n','#define COH_PRECISE precise\n'))+';\n'
for i in range(3):
    text+='static const char fragment_shader_'+str(i)+'[] = '+json.dumps('#version 300 es\n#define MATERIAL '+str(i)+'\n'+f)+';\n'
    text+='static const char fragment_shader_320_'+str(i)+'[] = '+json.dumps('#version 320 es\n#define MATERIAL '+str(i)+'\n'+f)+';\n'
args=argparse.ArgumentParser();args.add_argument('--check',action='store_true');a=args.parse_args()
out=p/'coh_renderer_shaders.h'
if a.check:
    assert out.read_text()==text,'stale shader header'
else:out.write_text(text)
